export type Product = { id: string; sku: string; name: string; price: number; stock: number; barcode?: string };
export type Seller = { id: string; name: string; active: boolean };
export type PaymentMethod = {
  id: string;
  name: string;
  type: string;
  active: boolean;
  isDefault?: boolean;
  source: 'BLING' | 'DEMO';
};
export type Coupon = { id: string; code: string; description: string; discount: number };
export type BlingCustomer = {
  id: string;
  cpf: string;
  name: string;
  email?: string;
  phone?: string;
};
export type FidelizeiCustomer = {
  id: string;
  cpf: string;
  name: string;
  tier: string;
  points: number;
  benefits: string[];
  coupons: Coupon[];
};
export type LookupStatus = 'FOUND' | 'NOT_FOUND' | 'UNAVAILABLE';
export type Customer = {
  found: boolean;
  cpf: string;
  name?: string;
  bling?: BlingCustomer;
  fidelizei?: FidelizeiCustomer;
  systems: { bling: LookupStatus; fidelizei: LookupStatus };
};
export type SaleItem = { productId: string; sku: string; name: string; quantity: number; unitPrice: number; comment?: string };
export type PaymentSplit = { paymentMethodId: string; paymentMethodName?: string; amount: number; receivedAmount?: number; change?: number };
export type Sale = {
  id: string;
  status: 'OPEN' | 'PROCESSING' | 'COMPLETED' | 'SYNC_FAILED' | 'RECONCILIATION_REQUIRED';
  operatorId: string;
  sellerId: string;
  cashSessionId: string;
  customer?: Customer;
  items: SaleItem[];
  coupon?: Coupon;
  reservationId?: string;
  paymentMethodId?: string;
  paymentMethodName?: string;
  payments?: PaymentSplit[];
  amountReceived?: number;
  change?: number;
  subtotal: number;
  discount: number;
  manualDiscount?: number;
  freight?: number;
  observations?: string;
  emitFiscal?: boolean;
  total: number;
  blingOrderId?: string;
  fiscalStatus?: 'NOT_REQUESTED' | 'REQUESTED' | 'FAILED';
  fidelizeiTransactionId?: string;
  lastError?: string;
  createdAt: string;
};
export const money = (n: number) => Math.round(n * 100) / 100;
